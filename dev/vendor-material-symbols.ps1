#!/usr/bin/env pwsh
# Regenerates Historia.Core/Components/IconPaths.Generated.cs from the checked-in
# Material Symbols SVG sources under assets/material-symbols/. Nothing is fetched from the network
# (constitution Rule 0) — the SVGs are vendored, pinned to the commit below.
#
#   Source repo  : google/material-design-icons
#   Pinned commit: 40a7a292a79d9394157e1ea24f83d52d5e17c556 (2026-09-11)
#   Style        : Outlined, wght 400, GRAD 0, FILL 0, opsz 24
#   Licence text : docs/third-party-licenses.md (Apache-2.0)
#
# Every glyph is a single path-data string on the Material 960-unit grid (viewBox 0 -960 960 960)
# and rendered in currentColor by ViewKit.IconGlyphPath. Re-running this script on an unchanged
# assets/material-symbols/ produces no diff (idempotent).

$ErrorActionPreference = 'Stop'
$PinnedCommit = '40a7a292a79d9394157e1ea24f83d52d5e17c556'

$root    = Split-Path -Parent $PSScriptRoot
$srcDir  = Join-Path $root 'assets/material-symbols'
$outFile = Join-Path $root 'Historia.Core/Components/IconPaths.Generated.cs'

function Get-Attr([string]$tag, [string]$name) {
    $m = [regex]::Match($tag, "$name\s*=\s*""([^""]*)""")
    if ($m.Success) { return $m.Groups[1].Value }
    return $null
}

$entries = [ordered]@{}
foreach ($file in Get-ChildItem -Path $srcDir -Filter '*.svg' | Sort-Object Name) {
    $name = [System.IO.Path]::GetFileNameWithoutExtension($file.Name)
    $svg  = Get-Content -Raw -Path $file.FullName
    $m = [regex]::Match($svg, '<path\b[^>]*>')
    if (-not $m.Success) { throw "No path element found in $($file.Name)" }
    $d = Get-Attr $m.Value 'd'
    if ([string]::IsNullOrWhiteSpace($d)) { throw "No path data 'd' found in $($file.Name)" }
    $entries[$name] = $d.Trim()
}

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('// <auto-generated>')
[void]$sb.AppendLine('//   Generated by dev/vendor-material-symbols.ps1 from assets/material-symbols/*.svg')
[void]$sb.AppendLine("//   google/material-design-icons @ $PinnedCommit")
[void]$sb.AppendLine('//   Outlined, wght 400, GRAD 0, FILL 0, opsz 24 (Apache-2.0) - see docs/third-party-licenses.md. Do not edit by hand.')
[void]$sb.AppendLine('// </auto-generated>')
[void]$sb.AppendLine()
[void]$sb.AppendLine('namespace Historia.Components;')
[void]$sb.AppendLine()
[void]$sb.AppendLine('public static partial class IconPaths')
[void]$sb.AppendLine('{')
[void]$sb.AppendLine('    /// <summary>Flattened Material Symbols glyph geometry (960-unit grid, viewBox 0 -960 960 960, fill, currentColor).</summary>')
[void]$sb.AppendLine('    internal static readonly IReadOnlyDictionary<string, string> MaterialSymbols =')
[void]$sb.AppendLine('        new Dictionary<string, string>(System.StringComparer.Ordinal)')
[void]$sb.AppendLine('        {')
foreach ($k in $entries.Keys) {
    $v = $entries[$k].Replace('"', '\"')
    [void]$sb.AppendLine("            [`"$k`"] = `"$v`",")
}
[void]$sb.AppendLine('        };')
[void]$sb.AppendLine('}')

$new = $sb.ToString() -replace "`r`n", "`n"
$existing = ''
if (Test-Path $outFile) { $existing = (Get-Content -Raw $outFile) -replace "`r`n", "`n" }

if ([string]::Equals($new, $existing, [System.StringComparison]::Ordinal)) {
    Write-Host "IconPaths.Generated.cs already up to date ($($entries.Count) glyphs)."
} else {
    Set-Content -Path $outFile -Value $new -NoNewline -Encoding utf8
    Write-Host "Wrote $outFile ($($entries.Count) glyphs)."
}
