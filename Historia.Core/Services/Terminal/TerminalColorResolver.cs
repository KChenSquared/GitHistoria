namespace Historia.Services.Terminal;

/// <summary>How an emulator cell colour is expressed.</summary>
public enum TerminalColorKind
{
    /// <summary>The terminal's default foreground (<c>term-fg</c>).</summary>
    DefaultForeground,

    /// <summary>The terminal's default background (<c>term-bg</c>).</summary>
    DefaultBackground,

    /// <summary>A palette index 0–255 (0–15 themed, 16–255 generated).</summary>
    Indexed,

    /// <summary>A 24-bit truecolor value, passed through unmapped.</summary>
    Rgb,
}

/// <summary>An emulator cell colour, before resolution to a concrete <see cref="Historia.Rgb"/>.</summary>
public readonly record struct TerminalColor(TerminalColorKind Kind, int Value)
{
    public static readonly TerminalColor DefaultForeground = new(TerminalColorKind.DefaultForeground, 0);
    public static readonly TerminalColor DefaultBackground = new(TerminalColorKind.DefaultBackground, 0);

    public static TerminalColor Indexed(int index) => new(TerminalColorKind.Indexed, index);

    public static TerminalColor FromRgb(int r, int g, int b)
        => new(TerminalColorKind.Rgb, ((r & 0xFF) << 16) | ((g & 0xFF) << 8) | (b & 0xFF));

    /// <summary>
    /// Interprets XTerm.NET's <c>(colour, mode)</c> pair. Mode 0 with the sentinel index
    /// (256 fg / 257 bg) is the default; mode 0 otherwise is a palette index; mode 1 is packed
    /// RGB.
    /// </summary>
    public static TerminalColor FromEmulator(int color, int mode, bool isBackground) => mode switch
    {
        1 => new TerminalColor(TerminalColorKind.Rgb, color & 0xFFFFFF),
        _ when color is >= 0 and <= 255 => Indexed(color),
        _ => isBackground ? DefaultBackground : DefaultForeground,
    };
}

/// <summary>
/// Resolves a <see cref="TerminalColor"/> to an <see cref="Historia.Rgb"/>. Indices 0–15
/// come from <see cref="HistoriaPalette"/>; 16–255 are generated by the standard xterm formulas
/// (computed, not colour literals); truecolor passes
/// through. Pure and unit-tested.
/// </summary>
public static class TerminalColorResolver
{
    /// <summary>Palette token per ANSI index 0–15, in the standard order.</summary>
    private static readonly string[] AnsiTokens =
    [
        "ansi-black", "ansi-red", "ansi-green", "ansi-yellow",
        "ansi-blue", "ansi-magenta", "ansi-cyan", "ansi-white",
        "ansi-br-black", "ansi-br-red", "ansi-br-green", "ansi-br-yellow",
        "ansi-br-blue", "ansi-br-magenta", "ansi-br-cyan", "ansi-br-white",
    ];

    public static Rgb Resolve(TerminalColor color, EffectiveTheme theme)
    {
        var palette = HistoriaPalette.For(theme);
        return color.Kind switch
        {
            TerminalColorKind.DefaultForeground => palette["term-fg"],
            TerminalColorKind.DefaultBackground => palette["term-bg"],
            TerminalColorKind.Rgb => Rgb.FromRgb((byte)((color.Value >> 16) & 0xFF), (byte)((color.Value >> 8) & 0xFF), (byte)(color.Value & 0xFF)),
            TerminalColorKind.Indexed when color.Value is >= 0 and <= 15 => palette[AnsiTokens[color.Value]],
            TerminalColorKind.Indexed when color.Value is >= 16 and <= 255 => FromIndex256(color.Value),
            TerminalColorKind.Indexed => palette["term-fg"], // out-of-range index: safe default
            _ => palette["term-fg"],
        };
    }

    /// <summary>
    /// The xterm 6×6×6 colour cube (indices 16–231) and the 24-step greyscale ramp (232–255).
    /// Indices 0–15 are themed and are not this function's job.
    /// </summary>
    public static Rgb FromIndex256(int index)
    {
        if (index is < 16 or > 255)
            throw new ArgumentOutOfRangeException(nameof(index), index, "FromIndex256 covers 16–255 only.");

        if (index <= 231)
        {
            var i = index - 16;
            var r6 = i / 36;
            var g6 = (i / 6) % 6;
            var b6 = i % 6;
            return Rgb.FromRgb(CubeChannel(r6), CubeChannel(g6), CubeChannel(b6));
        }

        var level = (byte)(8 + (index - 232) * 10);
        return Rgb.FromRgb(level, level, level);
    }

    private static byte CubeChannel(int c) => (byte)(c == 0 ? 0 : 55 + c * 40);
}
