namespace Historia.Services.CommandLine;

/// <summary>
/// Generates and parses Windows Registry Editor Version 5.00 (.reg) export files for user PATH backups.
/// </summary>
[SupportedOSPlatform("windows")]
public static class PathBackup
{
    private const string Header = "Windows Registry Editor Version 5.00";
    private const string SectionKey = "[HKEY_CURRENT_USER\\Environment]";
    private const string ValuePrefix = "\"Path\"=";
    private const string HexPrefix = "hex(2):";

    /// <summary>
    /// Builds a .reg file containing the specified user Path value and registry kind.
    /// </summary>
    public static string ToRegFile(string value, RegistryValueKind kind)
    {
        var sb = new StringBuilder();
        sb.Append(Header).Append("\r\n\r\n").Append(SectionKey).Append("\r\n");

        if (kind == RegistryValueKind.ExpandString)
        {
            sb.Append(ValuePrefix).Append(HexPrefix);
            var bytes = Encoding.Unicode.GetBytes(value);
            var allBytes = new byte[bytes.Length + 2];
            bytes.CopyTo(allBytes, 0);
            allBytes[^2] = 0;
            allBytes[^1] = 0;

            int lineLen = ValuePrefix.Length + HexPrefix.Length;
            for (int i = 0; i < allBytes.Length; i++)
            {
                var hex = allBytes[i].ToString("x2");
                bool isLast = i == allBytes.Length - 1;
                var token = isLast ? hex : hex + ",";

                if (lineLen + token.Length + (isLast ? 0 : 1) > 78 && !isLast)
                {
                    sb.Append("\\\r\n  ");
                    lineLen = 2;
                }

                sb.Append(token);
                lineLen += token.Length;
            }
            sb.Append("\r\n");
        }
        else
        {
            var escaped = value.Replace("\\", "\\\\").Replace("\"", "\\\"");
            sb.Append(ValuePrefix).Append('"').Append(escaped).Append("\"\r\n");
        }

        return sb.ToString();
    }

    /// <summary>
    /// Parses a .reg file generated by <see cref="ToRegFile"/> back into its Path value and registry kind.
    /// </summary>
    public static (string Value, RegistryValueKind Kind) FromRegFile(string regContent)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(regContent);

        if (!regContent.Contains(Header, StringComparison.Ordinal))
            throw new FormatException("Missing Windows Registry Editor header.");
        if (!regContent.Contains(SectionKey, StringComparison.Ordinal))
            throw new FormatException("Missing registry section key.");

        var pathIdx = regContent.IndexOf(ValuePrefix, StringComparison.Ordinal);
        if (pathIdx < 0)
            throw new FormatException("Missing Path value entry.");

        var afterPrefix = regContent[(pathIdx + ValuePrefix.Length)..];
        if (afterPrefix.StartsWith(HexPrefix, StringComparison.Ordinal))
        {
            var hexPayload = afterPrefix[HexPrefix.Length..];
            var sb = new StringBuilder();
            using var reader = new StringReader(hexPayload);
            string? line;
            while ((line = reader.ReadLine()) is not null)
            {
                var trimmed = line.Trim();
                if (trimmed.EndsWith('\\'))
                {
                    sb.Append(trimmed[..^1]);
                }
                else
                {
                    sb.Append(trimmed);
                    break;
                }
            }

            var tokens = sb.ToString().Split(',', StringSplitOptions.RemoveEmptyEntries);
            var bytes = new byte[tokens.Length];
            for (int i = 0; i < tokens.Length; i++)
            {
                bytes[i] = Convert.ToByte(tokens[i].Trim(), 16);
            }

            int lengthWithoutNull = bytes.Length;
            if (lengthWithoutNull >= 2 && bytes[^1] == 0 && bytes[^2] == 0)
                lengthWithoutNull -= 2;

            var val = Encoding.Unicode.GetString(bytes, 0, lengthWithoutNull);
            return (val, RegistryValueKind.ExpandString);
        }
        else if (afterPrefix.StartsWith('"'))
        {
            var sb = new StringBuilder();
            bool escaping = false;
            for (int i = 1; i < afterPrefix.Length; i++)
            {
                char c = afterPrefix[i];
                if (escaping)
                {
                    sb.Append(c);
                    escaping = false;
                }
                else if (c == '\\')
                {
                    escaping = true;
                }
                else if (c == '"')
                {
                    break;
                }
                else
                {
                    sb.Append(c);
                }
            }

            return (sb.ToString(), RegistryValueKind.String);
        }
        else
        {
            throw new FormatException("Unrecognized registry value format for Path.");
        }
    }
}
